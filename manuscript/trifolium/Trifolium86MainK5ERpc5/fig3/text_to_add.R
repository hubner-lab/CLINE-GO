#!/usr/bin/env Rscript
# Drafts the Results paragraph on stripes (user review 2026-10-16, note on as_qq; plan
# ~/.claude/plans/fancy-scribbling-garden.md, Phase 2). Every number is read here from a table, none typed:
#   stripe counts      manuscript_fig3/draft/lf_supp_panel_b.tsv (K = 5 rows; from snp_stripe_imputation.tsv, K5PC5)
#   LFMM inflation     manuscript_fig3/draft/lf_supp_panel_c.tsv (K = 5 rows, before genomic control)
#   EMMAX lambda       EMMAX_pvalues_K5.tsv, median chi2 per distinct predictor (no genomic control applied)
#   agreement set      gea_doc/gea_doc_numbers.tsv (v5.agreed, v5.stripe_n, c.clump_bp)
#   site names         fig3/site_names.tsv (coastal sites 28955 / 28960)
# Writes manuscript_fig3/text_to_add.md (merged into fig3.md in Phase 7; the manuscript itself goes through /write).
# Run inside the image from /pipeline: Rscript ANALYSIS/Trifolium86MainK5ERpc5/fig3/text_to_add.R
suppressPackageStartupMessages(library(data.table))
AN <- "/pipeline/ANALYSIS/Trifolium86MainK5ERpc5"
D  <- file.path(AN, "manuscript_fig3/draft")
N  <- fread(file.path(AN, "gea_doc/gea_doc_numbers.tsv"), sep = "\t", colClasses = "character")
tok <- function(k) { v <- N[key == k, value]; stopifnot(length(v) == 1); v }
b <- fread(file.path(D, "lf_supp_panel_b.tsv"))[K == "K = 5"]
cnt <- function(m) { x <- b[method == m]; c(rep = x[class == "in a repeated vector", n], all = sum(x$n)) }
e <- cnt("EMMAX"); r <- cnt("RDA"); l <- cnt("LFMM")
stopifnot(e[["all"]] == as.integer(tok("v5.emmax_snps")))
gif <- fread(file.path(D, "lf_supp_panel_c.tsv"))[K == "K = 5", gif]
stopifnot(length(gif) == 14)
em <- fread("/pipeline/Trifolium86MainK5ERpc5_results/GEA/tables/methods/EMMAX/EMMAX_pvalues_K5.tsv")
pred <- setdiff(grep("^bio_", names(em), value = TRUE), c("bio_11", "bio_19"))
lam <- sapply(pred, function(v) qchisq(median(em[[v]]), 1, lower.tail = FALSE) / qchisq(0.5, 1))
sites <- fread(file.path(AN, "fig3/site_names.tsv"), colClasses = "character")
coast <- sites[site_id %in% c("28955", "28960"), short]
pct <- function(x) sprintf("%.0f%%", 100 * x[["rep"]] / x[["all"]])
f <- function(x) formatC(x, big.mark = ",", format = "d")

txt <- sprintf(paste0(
"Both the Manhattan and the QQ plots of EMMAX show stripes: long runs of SNPs with near-identical P values. ",
"They are SNPs that share one genotype vector, private to a lineage and repeated at ten or more SNPs across the genome. ",
"With %s principal components, %s of the %s EMMAX-significant SNPs (%s) carried such a repeated vector, against %s of %s ",
"for RDA, although EMMAX itself was not inflated (median λ %.2f, range %.2f-%.2f over the %d distinct predictors). ",
"Requiring agreement with RDA within %s bp removed almost all of them: %s of the %s agreement SNPs lie in repeated vectors, ",
"all from the coastal indicator carried by sites %s and %s. ",
"LFMM, whose latent factors did not absorb the lineage structure, was affected far more: before genomic control its ",
"inflation factor had a median of %.1f (range %.1f-%.1f) across predictors, and %s of its %s significant SNPs (%s) ",
"were in repeated vectors. LFMM was therefore left out of the analysis (Fig. S#)."),
    tok("c.n_pcs"), f(e[["rep"]]), f(e[["all"]]), pct(e), f(r[["rep"]]), f(r[["all"]]),
    median(lam), min(lam), max(lam), length(lam),
    tok("c.clump_bp"), tok("v5.stripe_n"), tok("v5.agreed"), coast[1], coast[2],
    median(gif), min(gif), max(gif), f(l[["rep"]]), f(l[["all"]]), pct(l))

out <- file.path(AN, "manuscript_fig3/text_to_add.md")
writeLines(c("# Text to add (drafts for the manuscript; numbers generated by fig3/text_to_add.R)", "",
             "## Results, association: stripes and why LFMM was left out", "", strwrap(txt, 118), ""), out)
message("wrote ", out); cat(txt, "\n")
