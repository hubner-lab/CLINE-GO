#!/usr/bin/env Rscript
# =============================================================================
# mvp_write_sweep_config.R -- ONE config per seed for the scenario-era garden sweep.
#
# Supersedes the two-config, one-garden-at-a-time shape written by
# mvp_write_garden_configs.R (kept as the rollback path). Two pipeline changes
# made that shape unnecessary:
#
#   1. Climate.custom.future_tables takes a LIST, and every offset rule declares
#      all scenarios as outputs -- so one invocation covers all 42 gardens
#      instead of 42 invocations rewriting a single env table.
#   2. rda_offset_corrected is its own registered method -- so the corrected and
#      uncorrected RDA fits run in the SAME invocation instead of two passes.
#
# Net: 84 Snakemake invocations per seed -> 1. No clone lanes, so no
# mvp_clone_project.sh, no per-garden harvest, no .complete marker dance.
#
# Prerequisite: benchmarks/mvp_write_garden_env.R must have written the garden
# env tables to data/mvp/MVP{seed}/gardens/. Scenario name == file basename ==
# garden id, which is what makes the harvested layout reproducible.
#
# Usage:
#   Rscript benchmarks/mvp_write_sweep_config.R [--seeds=all|CSV] [--ntree=500] [--cpu=3]
#
# Writes: config_MVP{seed}_sweep.yaml  (project_name stays MVP{seed} -- the base tree)
# =============================================================================

suppressPackageStartupMessages(library(data.table))

PIPELINE_ROOT <- Sys.getenv("PIPELINE_ROOT", "/pipeline")
source(file.path(PIPELINE_ROOT, "benchmarks/lib_detection.R"))

args    <- parse_kv_args(commandArgs(trailingOnly = TRUE))
opt     <- function(k, d) if (is.null(args[[k]]) || !nzchar(args[[k]])) d else args[[k]]
SEEDS_A <- opt("seeds", "all")
NTREE   <- opt("ntree", "500")
CPU     <- as.integer(opt("cpu", "3"))
# Which garden set to declare as scenarios. Offset outputs live at per-scenario
# paths, so a sweep can be split into phases that each compute a DISJOINT set of
# gardens and then merge in the harvest -- phase 2 costs only the gardens phase 1
# did not run, instead of recomputing everything.
#   gardens_p1  the 42-garden journal-09 set (30 landscape + 12 novelty)
#   gardens_p2  the remaining 70 landscape gardens
#   gardens     all 112 (the full reciprocal-transplant design)
GARDEN_SUBDIR <- opt("gardens_subdir", "gardens")
SUFFIX        <- opt("suffix", "_sweep")

# Panel roster -- see mvp_write_garden_configs.R for what each panel means in
# Lind & Lotterhos vocabulary. Overridable with --sets so a sweep can run the
# CHEAP panels first: Gradient Forest build cost scales with panel SNP count, and
# `all` (~10-26k SNPs) plus `neutral_all` (~5k) are essentially the entire model
# cost, while truth/best/union/intersect3 are <=220 SNPs and build in seconds.
# Running the small panels first yields the headline claim (GEA-detected panels
# vs the QTN oracle) hours earlier; the reference/floor panels backfill after.
SETS <- strsplit(opt("sets", "all,neutral_all,truth,union,best,intersect3,rand_best1"), ",")[[1]]

MAN   <- fread(file.path(PIPELINE_ROOT, "benchmarks/mvp_seeds.tsv"),
               colClasses = c("seed" = "character"))
SEEDS <- if (SEEDS_A == "all") MAN$seed else strsplit(SEEDS_A, ",", fixed = TRUE)[[1]]

mala_block <- function(kbest) c(
    "",
    "#-----------------------------------------------------------------------------",
    "# MALADAPTATION -- scenario-era garden sweep (one invocation, all gardens).",
    "# Generated by benchmarks/mvp_write_sweep_config.R; do not hand-edit, regenerate.",
    "# All four offset implementations of Lind & Lotterhos 2025 in ONE pass:",
    "#   gradient_forest      GFoffset",
    "#   geometric_offset     LFMM2offset",
    "#   rda_offset           RDA-uncorrected (condition_pcs 0, canonical per B7)",
    "#   rda_offset_corrected RDA-corrected   (condition_pcs = k_best of this seed)",
    "#-----------------------------------------------------------------------------",
    "Maladaptation:",
    "  methods:",
    "    gradient_forest:",
    sprintf("      ntree: '%s'", NTREE),
    "      cor_threshold: '0.5'",
    "      spatial_correction: without",
    "      random_model: false",
    # MANDATORY for the garden sweep. common.smk:409 defaults this to TRUE, which pulls
    # `rule gf_sensitivity_check` (maladaptation.smk:241) into the DAG. That rule asks for the
    # DEFAULT future scenario (year{Future.year}_ssp{Future.ssp}), which is NOT one of the 112
    # garden env tables in SCENARIOS, so stage_custom_climate_future dies with
    # `KeyError: 'year2061-2080_ssp585'` in under 10 s -- for every seed, before any garden runs.
    # Cost the SS-Clines b3 block one full wave (logs_garden_ssclines_b3.run1_sensitivitycheck.log)
    # and b4 another, because b3's configs were patched by hand afterwards instead of here.
    "      sensitivity_check: false",
    "    geometric_offset:",
    "      scale: true",
    "      k: ''",
    "    rda_offset:",
    "      axes: 2                                # K_max on 2 predictors; measured, not guessed",
    "      axis_alpha: 0.05",
    "      permutations: 99                       # unused at axes: 2, kept low",
    "      condition_pcs: 0                       # RDA-uncorrected",
    "      seed: 42",
    "    rda_offset_corrected:",
    "      axes: 2",
    "      axis_alpha: 0.05",
    "      permutations: 99",
    sprintf("      condition_pcs: %d                       # RDA-corrected (k_best of this seed)", kbest),
    "      seed: 42",
    # Tables only: the sweep consumes genetic_offset_site.tsv and discards every plot.
    "  emit_plots: false",
    "  snp_sets:", paste0("    - ", SETS))

written <- 0L
for (s in SEEDS) {
    base <- file.path(PIPELINE_ROOT, sprintf("config_MVP%s.yaml", s))
    if (!file.exists(base)) { message("SKIP (no base config): ", base); next }

    gdir <- file.path(PIPELINE_ROOT, "data/mvp", sprintf("MVP%s", s), GARDEN_SUBDIR)
    tabs <- sort(list.files(gdir, pattern = "\\.tsv$"))
    if (!length(tabs)) {
        stop("no garden env tables in ", gdir,
             " -- run benchmarks/mvp_write_garden_env.R --seed=", s, " first")
    }

    kbest <- MAN[seed == s]$k_best
    if (!length(kbest) || is.na(kbest)) stop("no k_best for seed ", s, " in mvp_seeds.tsv")

    L <- readLines(base)
    if (any(grepl("^Maladaptation:", L))) stop("base config already has a Maladaptation block: ", base)

    i <- grep("^\\s*present_table:", L)
    if (length(i) != 1L) stop("expected exactly one present_table: line in ", base)
    indent <- sub("^(\\s*).*$", "\\1", L[i])
    L <- append(L, c(sprintf("%sfuture_tables:", indent),
                     sprintf("%s  - \"%s/%s\"", indent, GARDEN_SUBDIR, tabs)), after = i)

    # `cpu` MUST be set. Unset, common.smk takes os.cpu_count() - 2, which inside a
    # container is the HOST core count, and rda_offset declares `threads: CPU` --
    # so one job reserves every core and the sweep serialises.
    if (!any(grepl("^cpu:", L))) {
        j <- grep("^project_name:", L)
        L <- append(L, sprintf("cpu: %d   # caps rda_offset's `threads: CPU` request", CPU),
                    after = if (length(j)) j[1] else 0L)
    }

    out <- file.path(PIPELINE_ROOT, sprintf("config_MVP%s%s.yaml", s, SUFFIX))
    writeLines(c(L, mala_block(as.integer(kbest))), out)
    message(sprintf("wrote %s  (%d scenarios, k_best=%s)", basename(out), length(tabs), kbest))
    written <- written + 1L
}
message(sprintf("\n%d config(s) written", written))
